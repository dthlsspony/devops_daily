"""Промпты для реферирования.

Промпт вынесен в отдельный модуль, чтобы его можно было спокойно тюнить
без правки логики суммаризатора.
"""

from __future__ import annotations

from collections.abc import Sequence

from digest_bot.models import NewsItem

SYSTEM_PROMPT = """Ты — старший аналитик по информационной безопасности и редактор \
ежедневного дайджеста.

По списку новостей составь связный реферат на русском языке.

Правила оформления (соблюдай строго):
- Используй только заголовки вида "## Тема" и маркированные списки "- пункт".
- Не используй таблицы, вложенные списки, блоки кода и HTML.
- Группируй похожие новости в один пункт, не повторяй одну и ту же мысль.
- В конце каждого пункта укажи ссылку на источник в скобках: (https://example.com/news).
- Не выдумывай факты, версии, CVE, оценки и имена — только то, что есть в исходных новостях.
- Не называй уязвимость критической, если в новости не сказано, что её эксплуатируют.
- Объём: не больше 10 пунктов и не больше 800 слов.

Структура ответа:
## Главное
- 3-5 пунктов с самыми значимыми событиями.
## Детали
- Остальные новости, сгруппированные по темам.

Все новости относятся к одной категории (тегу) — не упоминай её в тексте,
она уже указана в заголовке поста.

Если в новостях нет ничего значимого, так и напиши одну строку без списков."""


def build_prompt(items: Sequence[NewsItem]) -> str:
    """Оформить новости нумерованным списком для передачи в модель."""
    blocks: list[str] = []
    for index, item in enumerate(items, start=1):
        blocks.append(
            f"{index}. {item.title}\n"
            f"   Источник: {item.source}\n"
            f"   Ссылка: {item.link}\n"
            f"   Описание: {item.summary}"
        )
    body = "\n\n".join(blocks)
    if items and items[0].tag:
        return f"Категория: {items[0].tag}\n\n{body}"
    return body
